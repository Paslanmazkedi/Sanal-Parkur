-- =============================================================================
-- Sanal Parkur — Duraklama (Workcube SETUP_PROD_PAUSE* karsiligi)
-- =============================================================================
-- Karar:
--   setup_prod_pause_types ZATEN VAR (cogul ad). Yeni TYPE tablosu acilmaz;
--   eksik Workcube kolonlari ALTER ile eklenir.
--   CAT ve PAUSE (olay) bu dosyada olusturulur.
--   downtime_events / downtime_reasons dokunulmaz; durus kalbi bu uc tablo.
--   SETUP_PROD_PAUSE_TYPE_ROW yok; kolonlar gelmeden yazilmaz.
--
-- Sema: production (saha tablolari; public degil).
-- =============================================================================

grant usage on schema production to service_role;
grant all privileges on all tables in schema production to service_role;
grant all privileges on all sequences in schema production to service_role;

-- -----------------------------------------------------------------------------
-- 1) Kategori — SETUP_PROD_PAUSE_CAT
-- -----------------------------------------------------------------------------
create table if not exists production.setup_prod_pause_cat (
  prod_pause_cat_id bigint generated by default as identity primary key,
  wex_prod_pause_cat_id bigint unique,
  prod_pause_cat varchar(100) not null,
  is_active boolean not null default true,
  is_working_time boolean not null default false,
  record_date timestamptz not null default now(),
  record_emp bigint,
  record_ip varchar(50),
  update_date timestamptz,
  update_emp bigint,
  update_ip varchar(50)
);

create index if not exists setup_prod_pause_cat_active_idx
on production.setup_prod_pause_cat (is_active)
where is_active = true;

-- -----------------------------------------------------------------------------
-- 2) Tip — mevcut setup_prod_pause_types (SETUP_PROD_PAUSE_TYPE)
-- -----------------------------------------------------------------------------
create table if not exists production.setup_prod_pause_types (
  prod_pause_type_id bigint generated by default as identity primary key,
  prod_pause_type_code varchar(50),
  prod_pause_type varchar(100) not null,
  prod_pause_cat_id bigint,
  is_active boolean default true
);

alter table production.setup_prod_pause_types
  add column if not exists wex_prod_pause_type_id bigint;

alter table production.setup_prod_pause_types
  add column if not exists pause_detail varchar(200);

alter table production.setup_prod_pause_types
  add column if not exists file_name varchar(100);

alter table production.setup_prod_pause_types
  add column if not exists product_catid bigint;

alter table production.setup_prod_pause_types
  add column if not exists record_date timestamptz default now();

alter table production.setup_prod_pause_types
  add column if not exists record_emp bigint;

alter table production.setup_prod_pause_types
  add column if not exists record_ip varchar(50);

alter table production.setup_prod_pause_types
  add column if not exists update_date timestamptz;

alter table production.setup_prod_pause_types
  add column if not exists update_emp bigint;

alter table production.setup_prod_pause_types
  add column if not exists update_ip varchar(50);

do $$
begin
  if not exists (
    select 1
    from pg_constraint
    where conname = 'setup_prod_pause_types_cat_fk'
  ) then
    alter table production.setup_prod_pause_types
      add constraint setup_prod_pause_types_cat_fk
      foreign key (prod_pause_cat_id)
      references production.setup_prod_pause_cat (prod_pause_cat_id)
      not valid;
  end if;
end $$;

create unique index if not exists setup_prod_pause_types_wex_id_uidx
on production.setup_prod_pause_types (wex_prod_pause_type_id)
where wex_prod_pause_type_id is not null;

create index if not exists setup_prod_pause_types_cat_idx
on production.setup_prod_pause_types (prod_pause_cat_id);

create index if not exists setup_prod_pause_types_active_idx
on production.setup_prod_pause_types (is_active)
where is_active is distinct from false;

-- -----------------------------------------------------------------------------
-- 3) Olay — SETUP_PROD_PAUSE
--    Insert: p_order_id dolu, pr_order_id NULL.
--    Sonuc girince: ayni p_order_id + pr_order_id IS NULL satirlara PR yazilir.
-- -----------------------------------------------------------------------------
create table if not exists production.setup_prod_pause (
  prod_pause_id bigint generated by default as identity primary key,
  wex_prod_pause_id bigint unique,
  prod_pause_type_id bigint
    references production.setup_prod_pause_types (prod_pause_type_id),
  prod_duration integer,
  prod_detail varchar(250),
  is_working_time boolean,
  pr_order_id bigint,
  action_date timestamptz,
  record_date timestamptz not null default now(),
  record_emp bigint,
  record_ip varchar(50),
  update_date timestamptz,
  update_emp bigint,
  update_ip varchar(50),
  duration_start_date timestamptz not null default now(),
  duration_finish_date timestamptz,
  operation_id bigint,
  employee_id bigint,
  station_id bigint,
  p_order_id bigint not null,
  operation_result_id bigint,
  source varchar(20) not null default 'operator'
    check (source in ('operator', 'iot', 'import', 'wex', 'system'))
);

create index if not exists setup_prod_pause_order_idx
on production.setup_prod_pause (p_order_id, duration_start_date desc);

create index if not exists setup_prod_pause_unbind_idx
on production.setup_prod_pause (p_order_id)
where pr_order_id is null;

create index if not exists setup_prod_pause_result_idx
on production.setup_prod_pause (pr_order_id)
where pr_order_id is not null;

create index if not exists setup_prod_pause_open_idx
on production.setup_prod_pause (station_id, duration_start_date desc)
where duration_finish_date is null;

create index if not exists setup_prod_pause_type_idx
on production.setup_prod_pause (prod_pause_type_id);

comment on table production.setup_prod_pause_cat is
  'Workcube SETUP_PROD_PAUSE_CAT — duraklama grubu';
comment on table production.setup_prod_pause_types is
  'Workcube SETUP_PROD_PAUSE_TYPE — duraklama nedeni (mevcut cogul tablo)';
comment on table production.setup_prod_pause is
  'Workcube SETUP_PROD_PAUSE — durus olayi; PR_ORDER_ID sonradan baglanir';
comment on column production.setup_prod_pause.pr_order_id is
  'Uretim sonuc. Insert NULL. Sonuc girince yalnizca NULL satirlara yazilir.';
grant select on production.setup_prod_pause_cat, production.setup_prod_pause_types, production.setup_prod_pause
  to anon, authenticated;
